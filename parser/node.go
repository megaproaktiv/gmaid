// declareNodeToken parses a single node token such as:
//
//	A
//	A[Label]
//	A{Decision}
//	A([Stadium])
//	A[(Database)]
//	A[/Parallelogram/]
//	A["Quoted <br/> label"]
//	A:::className   (class suffix is stripped/ignored)
//
// It returns the node id and ensures the node exists in the graph. If a label
// is present it updates the node's label and shape (last definition wins, as
// in mermaid).
func (p *parser) declareNodeToken(tok string) string {
	tok = strings.TrimSpace(tok)

	// Strip a trailing `:::class` shorthand.
	if idx := strings.Index(tok, ":::"); idx >= 0 {
		tok = strings.TrimSpace(tok[:idx])
	}

	id, shape, label, hasShape := splitIDAndShape(tok)
	n := p.g.EnsureNode(id)
	if hasShape {
		n.Shape = shape
		n.Label = label
	}
	return id
}

// splitIDAndShape separates the leading identifier from an optional shape
// wrapper. Returns id, shape, decoded label, and whether a shape was found.
func splitIDAndShape(tok string) (id string, shape model.Shape, label string, has bool) {
	// Find first shape-opening delimiter.
	open := strings.IndexAny(tok, "[({")
	if open < 0 {
		return tok, model.ShapeRect, tok, false
	}
	id = strings.TrimSpace(tok[:open])
	body := tok[open:]
	shape, inner := detectShape(body)
	return id, shape, cleanLabel(inner), true
}

// detectShape inspects the wrapper characters to classify the node shape and
// returns the inner (raw) label text.
func detectShape(body string) (model.Shape, string) {
	// Ordered from most-specific (longer delimiters) to least.
	type pat struct {
		open, close string
		shape       model.Shape
	}
	pats := []pat{
		{"([", "])", model.ShapeStadium},
		{"[(", ")]", model.ShapeCylinder},
		{"[[", "]]", model.ShapeSubroutine},
		{"((", "))", model.ShapeCircle},
		{"{{", "}}", model.ShapeHexagon},
		{"[/", "/]", model.ShapeParallelogram},
		{`[\`, `\]`, model.ShapeParallelogramAlt},
		{"[/", `\]`, model.ShapeTrapezoid},
		{`[\`, "/]", model.ShapeTrapezoidAlt},
		{"(", ")", model.ShapeRound},
		{"[", "]", model.ShapeRect},
		{"{", "}", model.ShapeDiamond},
	}
	// Trapezoid vs parallelogram share the `[/` opener; disambiguate by close.
	if strings.HasPrefix(body, "[/") {
		if strings.HasSuffix(body, `\]`) {
			return model.ShapeTrapezoid, trimEnds(body, 2, 2)
		}
		if strings.HasSuffix(body, "/]") {
			return model.ShapeParallelogram, trimEnds(body, 2, 2)
		}
	}
	if strings.HasPrefix(body, `[\`) {
		if strings.HasSuffix(body, "/]") {
			return model.ShapeTrapezoidAlt, trimEnds(body, 2, 2)
		}
		if strings.HasSuffix(body, `\]`) {
			return model.ShapeParallelogramAlt, trimEnds(body, 2, 2)
		}
	}
	for _, pt := range pats {
		if strings.HasPrefix(body, pt.open) && strings.HasSuffix(body, pt.close) &&
			len(body) >= len(pt.open)+len(pt.close) {
			return pt.shape, trimEnds(body, len(pt.open), len(pt.close))
		}
	}
	// Fallback: treat as rectangle with the whole body minus one char each end.
	return model.ShapeRect, trimEnds(body, 1, 1)
}

func trimEnds(s string, l, r int) string {
	if len(s) < l+r {
		return ""
	}
	return s[l : len(s)-r]
}

// cleanLabel normalizes a raw label: strips surrounding quotes/backticks,
// converts <br>, <br/>, <br /> and the literal escape \n to newlines, and
// decodes a couple of common HTML entities.
func cleanLabel(s string) string {
	s = strings.TrimSpace(s)
	s = strings.Trim(s, "\"")
	s = strings.TrimSpace(s)
	// backtick markdown strings
	s = strings.Trim(s, "`")

	repl := strings.NewReplacer(
		"<br/>", "\n",
		"<br />", "\n",
		"<br>", "\n",
		"<BR/>", "\n",
		"<BR>", "\n",
		`\n`, "\n",
		"&lt;", "<",
		"&gt;", ">",
		"&amp;", "&",
		"&quot;", "\"",
		"&nbsp;", " ",
		"#quot;", "\"",
	)
	s = repl.Replace(s)
	return strings.TrimSpace(s)
}

// parseSubgraphHeader parses the text after the `subgraph` keyword:
//
//	ID["Title"]  -> id=ID, title=Title
//	ID[Title]    -> id=ID, title=Title
//	Title        -> id=Title, title=Title
//	"Title"      -> id generated by caller? mermaid uses title as id
func parseSubgraphHeader(rest string) (id, title string) {
	rest = strings.TrimSpace(rest)
	if rest == "" {
		return "", ""
	}
	if open := strings.IndexAny(rest, "[("); open >= 0 {
		id = strings.TrimSpace(rest[:open])
		body := rest[open:]
		_, inner := detectShape(body)
		title = cleanLabel(inner)
		if id == "" {
			id = title
		}
		return id, title
	}
	// No bracket: whole thing is both id and title (strip quotes).
	title = cleanLabel(rest)
	id = title
	return id, title
}

// parseStyle parses a `style NODEID prop:val,prop:val` directive.
func (p *parser) parseStyle(line string) {
	fields := strings.Fields(line)
	if len(fields) < 3 {
		return
	}
	id := fields[1]
	rest := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line[len("style"):]), id))
	st := parseStyleProps(rest)
	n := p.g.EnsureNode(id)
	n.Style = st
}

func parseStyleProps(s string) *model.Style {
	st := &model.Style{}
	for _, part := range strings.Split(s, ",") {
		kv := strings.SplitN(part, ":", 2)
		if len(kv) != 2 {
			continue
		}
		k := strings.TrimSpace(strings.ToLower(kv[0]))
		v := strings.TrimSpace(kv[1])
		switch k {
		case "fill":
			st.Fill = v
		case "stroke":
			st.Stroke = v
		case "color":
			st.Color = v
		case "stroke-width":
			v = strings.TrimSuffix(v, "px")
			if f, err := strconv.ParseFloat(strings.TrimSpace(v), 64); err == nil {
				st.StrokeWidth = f
			}
		case "stroke-dasharray":
			st.Dashed = true
		}
	}
	return st
}

// --- small lexical helpers used by parser.go ---

// stripComment removes a trailing `%% ...` comment and `;` statement enders.
func stripComment(line string) string {
	if idx := strings.Index(line, "%%"); idx >= 0 {
		line = line[:idx]
	}
	return strings.TrimRight(strings.TrimRight(line, " \t"), ";")
}

// matchHeader recognizes `flowchart <dir>` or `graph <dir>`.
func matchHeader(line string) (kw string, dir model.Direction, ok bool) {
	fields := strings.Fields(line)
	if len(fields) == 0 {
		return "", "", false
	}
	switch strings.ToLower(fields[0]) {
	case "flowchart", "graph":
		kw = fields[0]
		if len(fields) >= 2 {
			dir = normalizeDir(fields[1])
		}
		return kw, dir, true
	}
	return "", "", false
}

// normalizeDir maps mermaid direction tokens to model.Direction.
func normalizeDir(s string) model.Direction {
	switch strings.ToUpper(strings.TrimSpace(s)) {
	case "TD", "TB":
		return model.DirTB
	case "LR":
		return model.DirLR
	case "BT":
		return model.DirBT
	case "RL":
		return model.DirRL
	}
	return ""
}
